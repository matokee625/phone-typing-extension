/**
 * Format number as Kenyan Shilling string
 */
export function formatKsh(amount) {
  if (amount === null || amount === undefined) return "KSh 0";
  return `KSh ${Number(amount).toLocaleString('en-KE')}`;
}

/**
 * Get all products belonging to a category by slug.
 */
export function getProductsByCategory(slug) {
  if (!slug) return products;
  return products.filter((product) => product.category === slug);
}

/**
 * Find a single product by its id or slug (supports both string and number).
 */
export function getProductById(id) {
  if (id === undefined || id === null) return undefined;
  return products.find(
    (product) =>
      String(product.id) === String(id) ||
      product.slug === String(id)
  );
}

/**
 * Return products that have a badge (featured items).
 */
export function getFeaturedProducts() {
  return products.filter((product) => product.badge !== null);
}

